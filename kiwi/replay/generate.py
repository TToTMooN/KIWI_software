"""Generate SA/DC descriptions from untouched CAD exports and the shared FR3 arm.

Run ``python -m kiwi.replay.generate [--check]`` after changing an import.
Calibrated ``camera_lens0`` links added to the source exports are preserved
and registered automatically. No camera pose is invented when absent.
"""

from __future__ import annotations

import argparse
import copy
import os
from pathlib import Path
import xml.etree.ElementTree as ET

import numpy as np
from scipy.spatial.transform import Rotation
import yaml

from kiwi.core.paths import descriptions_root

MODELS = {"chopstick_sa": "ChopstickSA.urdf", "chopstick_dc": "ChopstickDC.urdf"}
CAMERA = "insta360_x5__47d4ae39761d23bd9bfcc1d54af43414"
HOME = [0.0, -0.785398, 0.0, -2.356194, 0.0, 1.570796, 0.785398]
# Assembly clocking about the arm flange, independent of CAD axes.
FR3_MOUNT_YAW_DEG = -135.0
BANNER = (
    "Generated by python -m kiwi.replay.generate; edit the source exports or generator."
)


def _xml(element: ET.Element) -> str:
    element = copy.deepcopy(element)
    element.insert(0, ET.Comment(BANNER))
    ET.indent(element, space="  ")
    return ET.tostring(element, encoding="unicode") + "\n"


def _numbers(values) -> str:
    return " ".join(f"{float(v):.12g}" for v in values)


def _transform(origin: ET.Element | None) -> np.ndarray:
    t = np.eye(4)
    if origin is not None:
        t[:3, 3] = np.fromstring(origin.get("xyz", "0 0 0"), sep=" ")
        t[:3, :3] = Rotation.from_euler(
            "xyz", np.fromstring(origin.get("rpy", "0 0 0"), sep=" ")
        ).as_matrix()
    return t


def _pose(t: np.ndarray, *, urdf: bool) -> dict[str, str]:
    r = Rotation.from_matrix(t[:3, :3])
    if urdf:
        return {"xyz": _numbers(t[:3, 3]), "rpy": _numbers(r.as_euler("xyz"))}
    return {"pos": _numbers(t[:3, 3]), "quat": _numbers(r.as_quat(scalar_first=True))}


def gripper(root: Path, name: str) -> ET.Element:
    """Normalize CAD identifiers, retaining all supplied reference frames."""
    robot = ET.parse(root / name / MODELS[name]).getroot()
    robot.set("name", name)
    left = robot.find("joint[@name='rev_left']")
    right = robot.find("joint[@name='rev_right']")
    assert left is not None and right is not None
    mapping = {
        left.find("parent").get("link"): f"{name}_base",
        left.find("child").get("link"): f"{name}_left_jaw",
        right.find("child").get("link"): f"{name}_right_jaw",
    }
    for link in robot.findall("link"):
        link.set("name", mapping.get(link.get("name"), link.get("name")))
        # CAD dummy frame inertias are zero; fixed reference frames have no mass.
        if link.find("visual") is None and link.find("collision") is None:
            for inertial in link.findall("inertial"):
                link.remove(inertial)
    for ref in robot.findall("joint/parent") + robot.findall("joint/child"):
        ref.set("link", mapping.get(ref.get("link"), ref.get("link")))
    for mesh in robot.findall(".//mesh"):
        mesh.set(
            "filename",
            mesh.get("filename").replace(
                "package://assets/", f"package://{name}/assets/"
            ),
        )
    return robot


def flange_to_root(robot: ET.Element) -> np.ndarray:
    joint = next(
        j
        for j in robot.findall("joint")
        if j.find("child").get("link") == "franka_flange"
    )
    return np.linalg.inv(_transform(joint.find("origin")))


def fr3_mount_transform(robot: ET.Element) -> np.ndarray:
    """CAD attachment with configured clocking about the arm flange's Z axis."""
    clocking = np.eye(4)
    clocking[:3, :3] = Rotation.from_euler(
        "z", FR3_MOUNT_YAW_DEG, degrees=True
    ).as_matrix()
    return clocking @ flange_to_root(robot)


def _prefix(robot: ET.Element, prefix: str) -> ET.Element:
    robot = copy.deepcopy(robot)
    for node in robot.iter():
        if node is robot:
            continue
        if "name" in node.attrib:
            node.set("name", prefix + node.get("name"))
        if node.tag in ("parent", "child"):
            node.set("link", prefix + node.get("link"))
        if node.tag == "mimic":
            node.set("joint", prefix + node.get("joint"))
    return robot


def urdf(root: Path, name: str) -> str:
    if name in MODELS:
        return _xml(gripper(root, name))
    if name not in ("fr3_chopstick_sa", "fr3_dual_chopstick_sa"):
        raise ValueError(f"unknown generated description {name!r}")
    import xacro
    from kiwi.replay.render import install_ament_stub

    install_ament_stub(root)
    arm = ET.fromstring(
        xacro.process_file(str(root / "fr3/xacro/fr3_arm.urdf.xacro")).toxml()
    )
    tool = gripper(root, "chopstick_sa")
    joint = ET.SubElement(arm, "joint", name="chopstick_sa_mount", type="fixed")
    ET.SubElement(joint, "parent", link="fr3_link8")
    ET.SubElement(joint, "child", link="chopstick_sa_base")
    ET.SubElement(joint, "origin", **_pose(fr3_mount_transform(tool), urdf=True))
    arm.extend(tool)
    arm.set("name", name)
    if name == "fr3_chopstick_sa":
        return _xml(arm)
    dual = ET.Element("robot", name=name)
    ET.SubElement(dual, "link", name="world")
    for side, y in (("left", 0.4025), ("right", -0.4025)):
        dual.extend(_prefix(arm, side + "_"))
        joint = ET.SubElement(dual, "joint", name=f"{side}_base_joint", type="fixed")
        ET.SubElement(joint, "parent", link="world")
        ET.SubElement(joint, "child", link=f"{side}_base")
        ET.SubElement(joint, "origin", xyz=f"0 {y} 0", rpy="0 0 0")
    return _xml(dual)


def _mjcf_gripper(root: Path, name: str) -> ET.Element:
    import mujoco

    robot = gripper(root, name)
    for mesh in robot.findall(".//mesh"):
        mesh.set(
            "filename", str(root / mesh.get("filename").removeprefix("package://"))
        )
    ET.SubElement(
        ET.SubElement(robot, "mujoco"),
        "compiler",
        discardvisual="false",
        fusestatic="false",
    )
    spec = mujoco.MjSpec.from_string(ET.tostring(robot, encoding="unicode"))
    spec.compile()
    model = ET.fromstring(spec.to_xml())
    asset = model.find("asset")
    ET.SubElement(
        asset,
        "material",
        name="camera_glossy_black",
        rgba="0.039215686 0.039215686 0.039215686 1",
        specular="0.8",
        shininess="0.85",
        roughness="0.15",
        metallic="0",
    )
    for i, geom in enumerate(model.findall(".//geom")):
        visual = geom.get("contype") == "0"
        geom.set("group", "2" if visual else "3")
        geom.set("name", f"{name}_{'visual' if visual else 'collision'}_{i}")
        if geom.get("mesh") == CAMERA:
            geom.set("material", "camera_glossy_black")
            geom.attrib.pop("rgba", None)
    # Reference sites share the exact body frames imported from the URDF.
    for link, site in (
        ("hand_tcp", f"{name}_tcp"),
        ("gripper_origin", "attachment_site"),
        ("camera_lens0", f"{name}_camera_lens0"),
    ):
        body = model.find(f".//body[@name='{link}']")
        if body is not None:
            ET.SubElement(body, "site", name=site, size="0.001", group="4")
    contact = ET.SubElement(model, "contact")
    for jaw in ("left", "right"):
        ET.SubElement(
            contact, "exclude", body1=f"{name}_base", body2=f"{name}_{jaw}_jaw"
        )
    # The paired gears/finger tips are intentional contacts for kinematic replay.
    ET.SubElement(
        contact, "exclude", body1=f"{name}_left_jaw", body2=f"{name}_right_jaw"
    )
    equality = ET.SubElement(model, "equality")
    ET.SubElement(
        equality, "joint", joint1="rev_right", joint2="rev_left", polycoef="0 -1 0 0 0"
    )
    if name == "chopstick_sa":
        actuator = ET.SubElement(model, "actuator")
        limit = robot.find("joint[@name='rev_left']/limit")
        ET.SubElement(
            actuator,
            "position",
            name="gripper_actuator",
            joint="rev_left",
            kp="20",
            dampratio="1",
            ctrlrange=f"{limit.get('lower')} {limit.get('upper')}",
        )
    return model


def mjcf(root: Path, name: str) -> str:
    standalone = name in MODELS
    model = _mjcf_gripper(root, name if standalone else "chopstick_sa")
    if standalone:
        mesh_base = root / name / "mjcf"
    else:
        arm = ET.parse(root / "fr3/mjcf/components/fr3_arm.xml").getroot()
        model.set("model", name)
        compiler = model.find("compiler")
        compiler.set("meshdir", "../meshes")
        model.insert(1, ET.Element("include", file="components/fr3_common.xml"))
        tool_body = model.find("worldbody/body")
        tool_body.attrib.update(
            _pose(fr3_mount_transform(gripper(root, "chopstick_sa")), urdf=False)
        )
        flange = arm.find(".//body[@name='fr3_link8']")
        ET.SubElement(flange, "site", name="flange_site", size="0.001", group="4")
        flange.append(tool_body)
        model.remove(model.find("worldbody"))
        model.append(arm.find("worldbody"))
        model.find("actuator").extend(arm.find("actuator"))
        mesh_base = root / "fr3/meshes"
    for mesh in model.findall("asset/mesh"):
        mesh.set("file", os.path.relpath(mesh.get("file"), mesh_base))
    return _xml(model)


def _packages(name: str) -> dict:
    return {
        name: {
            "dir": name,
            "path_substitutions": {
                f"assets/{CAMERA}.stl": "assets/insta360_x5_glossy_black.glb"
            },
        }
    }


def registry(root: Path, family: str) -> str:
    if family in MODELS:
        frames = {link.get("name") for link in gripper(root, family).findall("link")}
        ee = {
            "default": {
                "urdf_link": "gripper_origin"
                if family == "chopstick_sa"
                else "chopstick_dc_base"
            },
            "tcp": {"urdf_link": "hand_tcp", "mjcf_site": f"{family}_tcp"},
        }
        if "franka_flange" in frames:
            ee["flange"] = {"urdf_link": "franka_flange"}
        if "camera_lens0" in frames:
            ee["camera"] = {
                "urdf_link": "camera_lens0",
                "mjcf_site": f"{family}_camera_lens0",
            }
        entry = {
            "urdf": f"{family}/urdf/{family}.urdf",
            "mjcf": f"{family}/mjcf/{family}.xml",
            "groups": {"gripper": {"joints": ["rev_left"]}},
            "end_effectors": ee,
            "render": {"generator": "imported_grippers"},
        }
        packages, descriptions = _packages(family), {family: entry}
    else:
        packages = {
            "franka_description": {
                "dir": "upstream/franka_description",
                "path_substitutions": {"meshes/robots/fr3/": "meshes/robots/fr3v2/"},
            },
            **_packages("chopstick_sa"),
        }
        ee = {
            "default": {"urdf_link": "gripper_origin", "mjcf_site": "attachment_site"},
            "tcp": {"urdf_link": "hand_tcp", "mjcf_site": "chopstick_sa_tcp"},
            "flange": {"urdf_link": "fr3_link8", "mjcf_site": "flange_site"},
        }
        if gripper(root, "chopstick_sa").find("link[@name='camera_lens0']") is not None:
            ee["camera"] = {
                "urdf_link": "camera_lens0",
                "mjcf_site": "chopstick_sa_camera_lens0",
            }
        group = {"joints": [f"fr3_joint{i}" for i in range(1, 8)], "home": HOME}
        descriptions = {
            "fr3_chopstick_sa": {
                "urdf": "fr3/urdf/fr3_chopstick_sa.urdf",
                "mjcf": "fr3/mjcf/fr3_chopstick_sa.xml",
                "groups": {"arm": group},
                "end_effectors": ee,
                "render": {"generator": "imported_grippers"},
            }
        }
        dual_groups = {
            f"{s}_arm": {"joints": [f"{s}_{j}" for j in group["joints"]], "home": HOME}
            for s in ("left", "right")
        }
        dual_ee = {
            f"{s}_{role}": {"urdf_link": f"{s}_{value['urdf_link']}"}
            for s in ("left", "right")
            for role, value in ee.items()
        }
        dual_ee.update(
            {
                role: {"urdf_link": f"left_{ee[role]['urdf_link']}"}
                for role in ("default", "tcp")
            }
        )
        descriptions["fr3_dual_chopstick_sa"] = {
            "urdf": "fr3/urdf/fr3_dual_chopstick_sa.urdf",
            "groups": dual_groups,
            "end_effectors": dual_ee,
            "render": {"generator": "imported_grippers"},
        }
    return (
        "# "
        + BANNER
        + "\n"
        + yaml.safe_dump(
            {
                "schema": "robot_descriptions_v1",
                "family": family,
                "packages": packages,
                "descriptions": descriptions,
            },
            sort_keys=False,
        )
    )


def outputs(root: Path) -> dict[Path, str | bytes]:
    import trimesh

    files: dict[Path, str | bytes] = {}
    for name in (*MODELS, "fr3_chopstick_sa", "fr3_dual_chopstick_sa"):
        family = name if name in MODELS else "fr3"
        files[root / family / "urdf" / f"{name}.urdf"] = urdf(root, name)
        if name != "fr3_dual_chopstick_sa":
            files[root / family / "mjcf" / f"{name}.xml"] = mjcf(root, name)
    for family in (*MODELS, "fr3"):
        files[root / family / "meta.yaml"] = registry(root, family)
    for name in MODELS:
        assets = root / name / "assets"
        mesh = trimesh.load_mesh(assets / f"{CAMERA}.stl")
        mesh.visual = trimesh.visual.TextureVisuals(
            material=trimesh.visual.material.PBRMaterial(
                name="Insta360 glossy black",
                baseColorFactor=[10, 10, 10, 255],
                metallicFactor=0.0,
                roughnessFactor=0.15,
            )
        )
        files[assets / "insta360_x5_glossy_black.glb"] = mesh.export(file_type="glb")
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    drift = False
    for path, data in outputs(descriptions_root()).items():
        content = data.encode() if isinstance(data, str) else data
        if args.check:
            if not path.exists() or path.read_bytes() != content:
                print(f"DRIFT {path}")
                drift = True
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
            print(f"Wrote {path}")
    return int(drift)


if __name__ == "__main__":
    raise SystemExit(main())
